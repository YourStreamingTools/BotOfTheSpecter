import { useEffect, useRef, useState } from 'react'
import { get } from '../../bot'

// Port of dashboard/logs.php: the language notice, the left card (log type,
// rotation, log time clock, Reload / Auto-refresh / Download) and the log
// box on the right. Endpoint: public/api/logs/logs.php (read only).
const API = '/api/logs/logs.php'
const TYPES: [string, string][] = [['bot', 'Bot Log'], ['chat', 'Chat Log'], ['twitch', 'Twitch Log'], ['api', 'API Log'], ['chat_history', 'Chat History'], ['event_log', 'Event Log'], ['websocket', 'Websocket Log'], ['system', 'System Log'], ['integrations', 'Integrations Log'], ['crash', 'Crash Log']]
type Rot = { value: number | string; label: string }
const CLS: Record<string, string> = { e67e22: 'lg-date', '3498db': 'lg-info', e74c3c: 'lg-err', f39c12: 'lg-warn', '95a5a6': 'lg-debug' }
// The server escapes the log text and only adds coloured spans; swap their inline colours for theme classes.
const tint = (h: string) => h.replace(/<span style="color: #([0-9a-f]{6}); font-weight: bold;">/g, (_, c: string) => `<span class="${CLS[c] ?? 'lg-date'}">`)
const pad = (n: number) => String(n).padStart(2, '0')
const stamp = (d: Date) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`

export default function Logs() {
  const [type, setType] = useState(''), [rots, setRots] = useState<Rot[]>([]), [rot, setRot] = useState('0')
  const [html, setHtml] = useState<string | null>(null), [err, setErr] = useState(''), [busy, setBusy] = useState(false)
  const [auto, setAuto] = useState(false), [now, setNow] = useState(() => new Date())
  const box = useRef<HTMLDivElement>(null), seq = useRef(0)
  useEffect(() => { const h = setInterval(() => setNow(new Date()), 1000); return () => clearInterval(h) }, [])
  async function load(t = type, r = rot) {
    if (!t) return
    const n = ++seq.current
    setBusy(true)
    try {
      const d = await get<{ data?: string; error?: string }>(`${API}?log=${t}&rotation=${r}`, 20000)
      if (n !== seq.current) return
      if (d.error) { setErr(`Error: ${d.error}`); setHtml(null) } else { setErr(''); setHtml(tint(d.data ?? '')) }
    } catch (e) { if ((e as Error).message !== 'http_401' && n === seq.current) { setErr('Network error: Failed to fetch log data'); setHtml(null) } }
    finally { if (n === seq.current) setBusy(false) }
  }
  async function pick(t: string) {
    setType(t); setRot('0'); setRots([]); setHtml(null); setErr('')
    if (!t) return
    get<{ rotations?: Rot[] }>(`${API}?list_rotations=${t}`, 20000).then((d) => setRots(Array.isArray(d.rotations) ? d.rotations : [])).catch(() => setRots([]))
    load(t, '0')
  }
  useEffect(() => { if (!auto || !type) return; const h = setInterval(() => load(), 5000); return () => clearInterval(h) }, [auto, type, rot]) // eslint-disable-line react-hooks/exhaustive-deps
  useEffect(() => { if (box.current) box.current.scrollTop = box.current.scrollHeight }, [html])
  const label = TYPES.find(([v]) => v === type)?.[1]
  return (
    <div className="page cmds cm">
      <div className="notice notice-warn"><i className="fas fa-language" /> <span>Note: All logs generated by the bot are always recorded in English, regardless of your dashboard language.</span></div>
      <div className="lg-layout">
        <section className="card lg-side" aria-label="Log controls">
          <label className="fld"><span className="fld-label">Select a log to view:</span>
            <select className="input cm-in" value={type} onChange={(e) => pick(e.target.value)}>
              <option value="">SELECT A LOG TYPE</option>
              {TYPES.map(([v, l]) => <option key={v} value={v}>{l}</option>)}
            </select></label>
          {rots.length > 1 && <label className="fld"><span className="fld-label">Log Rotation:</span>
            <select className="input cm-in" value={rot} onChange={(e) => { setRot(e.target.value); load(type, e.target.value) }}>
              {rots.map((r) => <option key={String(r.value)} value={String(r.value)}>{r.label}</option>)}
            </select></label>}
          <p className="muted small">Log Time is GMT+{now.getTimezoneOffset() === -660 ? 11 : 10}</p>
          <p className="small"><b>Current Log Time:</b> <span className="lg-clock">{stamp(now)}</span></p>
          {type && <div className="lg-btns">
            <button type="button" className="btn cm-btn" disabled={busy} onClick={() => load()}>Reload Log</button>
            <button type="button" className="btn btn-quiet cm-btn" aria-pressed={auto} onClick={() => setAuto(!auto)}>Auto-refresh: {auto ? 'ON' : 'OFF'}</button>
            <a className="btn btn-ok cm-btn" href={`${API}?download_log=${type}&rotation=${rot}`} download><i className="fas fa-download" /> Download</a>
          </div>}
        </section>
        <section className="card lg-main" aria-label="Log">
          <h3 className="card-h"><i className="fas fa-file-lines" /> {label ?? 'Logs'}</h3>
          <div ref={box} className="adm-log lg-box" aria-busy={busy} aria-live="polite">
            {err ? <span className="cm-no">{err}</span>
              : html !== null ? <span dangerouslySetInnerHTML={{ __html: html }} />
              : busy ? <div className="adm-log-skel" aria-hidden="true">{[90, 70, 85, 60, 95, 75].map((w, k) => <span key={k} className="bp-skel" style={{ width: `${w}%` }} />)}</div>
              : <span className="muted">Select a log type to view its contents.</span>}
          </div>
        </section>
      </div>
    </div>
  )
}
